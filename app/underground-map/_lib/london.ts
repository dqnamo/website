// Hops whose automatic shape could cut through a station they don't serve, pinned to the shape that
// doesn't: [from, to, route mode as seen from `from`].
const SHAPES: [from: string, to: string, mode: RouteMode][] = [
  ["WLO", "KEN", 1],
  ["BTG", "MLE", 1],
  ["BKS", "FNR", 1],
  ["HMD", "ACT", 1],
  ["CAM", "EUS", 1],
];

export function londonDoc(grid: number): MapDoc {
  const ids: Record<string, string> = {};
  const stations: Station[] = Object.entries(STATIONS).map(
    ([key, [name, x, y]]) => {
      ids[key] = uid();
      return { id: ids[key], name, x: x * grid, y: y * grid, label: null };
    },
  );
  const lines = LINES.map(([name, color]) => ({ id: uid(), name, color }));
  const segments: Segment[] = [];
  LINES.forEach(([, , branches], i) => {
    for (const branch of branches) {
      const stops = branch.split(" ");
      for (let j = 0; j < stops.length - 1; j++) {
        segments.push({
          id: uid(),
          line: lines[i].id,
          a: ids[stops[j]],
          b: ids[stops[j + 1]],
        });
      }
    }
  });
  // A route's shape is stored against the pair's first station by id, so flip it when that's `to`.
  const routes: MapDoc["routes"] = {};
  for (const [from, to, mode] of SHAPES) {
    const key = pairKey(ids[from], ids[to]);
    const flipped = !key.startsWith(`${ids[from]}|`);
    routes[key] = flipped && mode !== 0 ? (mode === 1 ? 2 : 1) : mode;
  }
  return { title: "London Underground", stations, lines, segments, routes };
}
